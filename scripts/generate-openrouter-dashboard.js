#!/usr/bin/env node

// Fetch OpenRouter key usage and emit a Kindle-sized SVG.
// Credentials stay in the caller environment; never print them.

const fs = require('node:fs');

const apiKey = process.env.OPENROUTER_API_KEY;
const output = process.env.DASHBOARD_SVG || 'out/openrouter-dashboard.svg';
const apiUrl = process.env.OPENROUTER_API_URL || 'https://openrouter.ai/api/v1/key';
const width = 1072;
const height = 1448;

function number(value) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
}

function esc(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function money(value) {
  return value == null ? '—' : `$${value.toFixed(2)}`;
}

function row(label, value, y) {
  return `<text x="72" y="${y}" class="label">${esc(label)}</text>` +
    `<text x="1000" y="${y}" text-anchor="end" class="value">${esc(value)}</text>`;
}

function renderSvg(data, now = new Date()) {
  const daily = number(data.usage_daily);
  const weekly = number(data.usage_weekly);
  const monthly = number(data.usage_monthly);
  const remaining = number(data.limit_remaining);

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <rect width="100%" height="100%" fill="white"/>
  <style>
    .title { font: 700 58px sans-serif; }
    .subtitle { font: 28px sans-serif; }
    .heading { font: 700 38px sans-serif; }
    .label { font: 700 34px sans-serif; }
    .value { font: 34px sans-serif; }
    .small { font: 26px sans-serif; }
  </style>
  <text x="72" y="108" class="title">OPENROUTER</text>
  <line x1="72" y1="140" x2="1000" y2="140" stroke="black" stroke-width="6"/>
  <text x="72" y="205" class="subtitle">Usage snapshot</text>
  <text x="1000" y="205" text-anchor="end" class="subtitle">${esc(now.toISOString().slice(0, 16).replace('T', ' '))} UTC</text>
  <text x="72" y="300" class="heading">SPEND</text>
  ${row('Today', money(daily), 380)}
  ${row('This week', money(weekly), 450)}
  ${row('This month', money(monthly), 520)}
  <line x1="72" y1="570" x2="1000" y2="570" stroke="black" stroke-width="3"/>
  <text x="72" y="650" class="heading">LIMIT</text>
  ${row('Remaining', money(remaining), 730)}
  <text x="72" y="830" class="heading">STATUS</text>
  <text x="72" y="910" class="label">Last successful update</text>
  <text x="72" y="970" class="small">OpenRouter API key endpoint</text>
  <text x="72" y="1330" class="small">Generated by GitHub Actions</text>
  <text x="72" y="1375" class="small">If stale, check workflow status.</text>
</svg>`;
}

async function fetchUsage(key, endpoint = apiUrl) {
  const response = await fetch(endpoint, {
    headers: { Authorization: `Bearer ${key}` },
    signal: AbortSignal.timeout(15000),
  });
  if (!response.ok) throw new Error(`OpenRouter HTTP ${response.status}`);
  const payload = await response.json();
  const data = payload && payload.data;
  if (!data || typeof data !== 'object') throw new Error('OpenRouter returned invalid key data');

  return data;
}

async function main() {
  if (!apiKey) {
    console.error('OPENROUTER_API_KEY is required');
    process.exit(2);
  }
  const data = await fetchUsage(apiKey);
  const svg = renderSvg(data);

  fs.mkdirSync(require('node:path').dirname(output), { recursive: true });
  fs.writeFileSync(output, svg, 'utf8');
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error.message || error);
    process.exit(1);
  });
}

module.exports = { fetchUsage, renderSvg };
